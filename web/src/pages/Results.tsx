import { useState } from 'react'
import { AccuracyByVariant, ConfusionMatrix, LatencyChart, Pareto, PerClassF1, Reliability, RobustnessChart, TrainingCurves } from '@/components/charts'
import { Empty, Figure, HeaderSummary, Loading, PageHeader, SafetyLabel, Section, Select, Tabs } from '@/components/ui'
import { figureUrl, useApi, useMetrics } from '@/lib/api'
import { ALL_MODELS, MODEL_NAMES, ZTA_MODELS, num } from '@/lib/format'
import type { Meta, Metrics, Robustness } from '@/lib/types'

export function ResultsTable({ M, models, large = false }: { M: Metrics; models: string[]; large?: boolean }) {
  return (
    <div className="overflow-x-auto">
      <table className={`list num ${large ? '[&_td]:!py-3 [&_td]:text-[19px] [&_th]:!text-[13px]' : ''}`}>
        <thead>
          <tr>
            <th>Model</th><th>ztachip</th><th className="r">Params</th><th className="r">MACs</th><th className="r">FP32</th>
            <th className="r">INT8 per-ch.</th><th className="r">INT8 per-tensor</th><th className="r">Agrees</th><th className="r">Size</th><th className="r">UINT8</th>
          </tr>
        </thead>
        <tbody>
          {models.map((m) => {
            const v = M[m].variants, p = M[m].profile
            return (
              <tr key={m}>
                <td className="font-medium text-ink">{MODEL_NAMES[m]}</td>
                <td>{M[m].ztachip_compatible ? <SafetyLabel tone="safe">Runs</SafetyLabel> : <SafetyLabel tone="danger">Would hang</SafetyLabel>}</td>
                <td className="r figure-sm text-ink-2">{num(p.params)}</td>
                <td className="r figure-sm text-ink-2">{(p.macs / 1e6).toFixed(1)} M</td>
                <td className="r figure-sm text-ink-2">{(v.keras.top1 * 100).toFixed(2)}%</td>
                <td className="r figure-sm text-ink-3">{(v.int8_pc.top1 * 100).toFixed(2)}%</td>
                <td className="r figure-sm text-ink-2">{(v.int8_pt.top1 * 100).toFixed(2)}%</td>
                <td className="r figure-sm text-ink-2">{(v.uint8.agreement_with_keras! * 100).toFixed(1)}%</td>
                <td className="r figure-sm text-ink-2">{v.uint8.size_kib!.toFixed(0)} KiB</td>
                <td className="r figure font-medium text-ink">{(v.uint8.top1 * 100).toFixed(2)}%</td>
              </tr>
            )
          })}
        </tbody>
      </table>
    </div>
  )
}

const KINDS = ['gaussian_noise', 'gaussian_blur', 'brightness', 'contrast', 'jpeg']

export default function Results() {
  const { data: M, loading } = useMetrics()
  const { data: meta } = useApi<Meta>('/api/meta')
  const { data: R } = useApi<Robustness>('/api/robustness', 'robustness')
  const [cmModel, setCmModel] = useState('zta_plain')
  const [cmVar, setCmVar] = useState<'keras' | 'uint8'>('uint8')
  const [curve, setCurve] = useState<'accuracy' | 'loss'>('accuracy')
  const [kind, setKind] = useState('gaussian_noise')
  if (loading) return <Loading />
  if (!M) return <Empty title="No results yet">Run <code className="inline-code">make eval figures</code>, then reload.</Empty>

  const models = ALL_MODELS.filter((m) => m in M)
  const zta = ZTA_MODELS.filter((m) => m in M)
  const classes = meta?.classes ?? []
  const dm = meta?.deploy_model ?? 'zta_plain'
  const figs = new Set(meta?.figures ?? [])
  const env = M._env
  const robModel = R ? Object.keys(R)[0] : null

  return (
    <>
      <PageHeader eyebrow="Evidence · Results" title="Accuracy holds all the way to the uint8 model"
        trailing={<HeaderSummary parts={[`${num(env?.test_images ?? 10000)} test images`, env?.cpu ?? 'CPU', `TF ${env?.tensorflow ?? ''}`]} />}>
        <p>Every number comes from the CIFAR-10 test set and is regenerated by <code>make eval</code>; the UINT8 column is the exact file deployed to ztachip.</p>
      </PageHeader>

      <Section kicker="01 / Summary">
        <ResultsTable M={M} models={models} />
      </Section>

      <Section kicker="02 / Quantization">
        <Figure caption="Test accuracy after each quantization stage. INT8 per-channel is TensorFlow’s default and cannot run on ztachip; INT8 per-tensor is rewritten to UINT8 for deployment.">
          <AccuracyByVariant M={M} models={models} />
        </Figure>
      </Section>

      <Section kicker="03 / Training" trailing={<Tabs value={curve} onChange={setCurve} options={[{ value: 'accuracy', label: 'Accuracy' }, { value: 'loss', label: 'Loss' }]} />}>
        <Figure caption="Solid lines are validation, dashed lines the augmented training set. ZTA-Plain trained for 40 epochs and the other models for 25, each with cosine learning-rate decay; the best validation checkpoint is kept.">
          <TrainingCurves models={models} metric={curve} />
        </Figure>
      </Section>

      <Section kicker="04 / Errors" trailing={
        <div className="flex items-center gap-4">
          <Select value={cmModel} onChange={setCmModel} options={models.map((m) => ({ value: m, label: MODEL_NAMES[m] }))} />
          <Tabs value={cmVar} onChange={setCmVar} options={[{ value: 'keras', label: 'FP32' }, { value: 'uint8', label: 'UINT8' }]} />
        </div>}>
        <div className="grid gap-10 lg:grid-cols-[1.15fr_1fr]">
          <Figure caption="Confusion matrix. The diagonal counts correct predictions; rose cells are confusions.">
            <ConfusionMatrix cm={M[cmModel].variants[cmVar].confusion} classes={classes} />
          </Figure>
          <Figure caption="Per-class F1 score for FP32 and UINT8. For ZTA-Plain, cat and dog are the hardest classes, and dog → cat is the most frequent confusion.">
            <PerClassF1 M={M} model={cmModel} classes={classes} />
          </Figure>
        </div>
      </Section>

      <Section kicker="05 / Efficiency and calibration">
        <div className="grid gap-10 lg:grid-cols-2">
          <Figure caption="UINT8 accuracy against compute; marker size is parameter count.">
            <Pareto M={M} models={models} />
          </Figure>
          <Figure caption={`Calibration of ${MODEL_NAMES[dm]}: confidence against actual accuracy. The dashed diagonal is perfect calibration.`}>
            <Reliability M={M} model={dm} />
          </Figure>
        </div>
      </Section>

      <Section kicker="06 / Latency">
        <Figure caption="CPU latency, batch 1, median of 500 single-thread runs. XNNPACK accelerates FP32 and INT8 but not legacy UINT8 kernels, so UINT8 is slow on a CPU; ztachip executes UINT8 in hardware. An Apple M4 is a high-end laptop processor, so the fair Phase II comparison is energy per inference on the ZedBoard, against its own ARM CPU.">
          <LatencyChart M={M} models={models} />
        </Figure>
        <table className="list mt-6">
          <thead><tr><th>Model</th><th>Theoretical ztachip lower bound</th><th className="r">Bound</th></tr></thead>
          <tbody>
            {zta.map((m) => (
              <tr key={m}>
                <td className="font-medium">{MODEL_NAMES[m]}</td>
                <td className="text-secondary text-ink-2">max(2·MACs / 20 GOPS, bytes / 1.2 GB/s), from ztachip’s published figures. Not a measurement.</td>
                <td className="r figure">{M[m].profile.zta_bound_ms.toFixed(3)} ms</td>
              </tr>
            ))}
          </tbody>
        </table>
      </Section>

      {R && robModel && (
        <Section kicker="07 / Robustness" trailing={<Tabs value={kind} onChange={setKind} options={KINDS.map((k) => ({ value: k, label: k.replace('_', ' ') }))} />}>
          <div className="grid gap-10 lg:grid-cols-[1.4fr_1fr]">
            <Figure caption={`${MODEL_NAMES[robModel]} under camera-like corruptions: 2,000 test images, five severities, in the spirit of CIFAR-10-C. For ZTA-Plain, FP32 and UINT8 stay within 1.5 points of each other at every severity: quantization does not make the model more fragile.`}>
              <RobustnessChart R={R} model={robModel} kind={kind} />
            </Figure>
            {figs.has('corruption_examples.png') && (
              <Figure caption="Example corruptions, severity 0–5.">
                <img src={figureUrl('corruption_examples.png')} alt="Corruption examples" className="w-full rounded-md" />
              </Figure>
            )}
          </div>
        </Section>
      )}

      {(figs.has(`gradcam_${dm}.png`) || figs.has(`mistakes_${dm}.png`)) && (
        <Section kicker="08 / Explainability">
          <div className="space-y-8">
            {figs.has(`gradcam_${dm}.png`) && (
              <Figure caption="Grad-CAM on random test images: the last 8×8 feature map weighted by the predicted class’s gradient, upsampled onto the input.">
                <img src={figureUrl(`gradcam_${dm}.png`)} alt="Grad-CAM examples" className="w-full" />
              </Figure>
            )}
            {figs.has(`mistakes_${dm}.png`) && (
              <Figure caption="The most confident mistakes of the UINT8 model.">
                <img src={figureUrl(`mistakes_${dm}.png`)} alt="Most confident mistakes" className="w-full" />
              </Figure>
            )}
          </div>
        </Section>
      )}
    </>
  )
}
